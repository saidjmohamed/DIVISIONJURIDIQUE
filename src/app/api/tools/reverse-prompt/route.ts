import { NextRequest, NextResponse } from 'next/server';
import { callAI, checkRateLimit } from '@/lib/ai-core';

export const maxDuration = 60;

const SYSTEM_PROMPT = `أنت خبير في الهندسة العكسية للنصوص القانونية وصياغة البرومبتات للمحامين الجزائريين.
مهمتك: تحليل المذكرة أو العريضة التي يرسلها المستخدم واستخراج "برومبت وصف عكسي" قابل لإعادة الاستخدام لإنشاء وثيقة قانونية جديدة بنفس البنية والأسلوب والشكل والصياغة، من دون نقل موضوع القضية الأصلية أو هوية أطرافها.

حلل بدقة:
1) نوع الوثيقة وبنيتها العامة.
2) الترويسة وموقع المحكمة/الجهة والبيانات الشكلية بصيغة placeholders فقط.
3) ترتيب العناوين والأقسام والفروع.
4) طريقة افتتاح النص والانتقال بين الأجزاء.
5) أسلوب صياغة الدفوع والحجج القانونية.
6) طريقة إدماج النصوص والمواد القانونية والاجتهاد القضائي إن وجدت، دون إعادة استعمال محتوى القضية الأصلية.
7) أسلوب الربط والاستنتاج والتعليل.
8) طول الفقرات وكثافتها ونمط التعداد والترقيم.
9) المصطلحات والأسلوب القانوني الرسمي الجزائري.
10) صياغة الطلبات والخاتمة والتوقيع.
11) أي خصائص شكلية أو لغوية ثابتة يمكن تعميمها.
12) درجة الرسمية والنبرة ومستوى التفصيل.

قواعد صارمة للخصوصية والتجريد:
- لا تذكر أسماء الأطراف أو المحامين أو الشهود أو الأشخاص.
- لا تذكر رقم القضية أو الأرقام الخاصة بالملف.
- لا تكشف موضوع النزاع أو الوقائع الخاصة بالقضية.
- لا تنسخ عبارات مميزة مرتبطة بالقضية إذا كانت تكشف موضوعها.
- لا تستنتج أو تخمّن موضوع القضية من النص.
- لا تعيد إنتاج المواد أو الوقائع الخاصة إلا إذا كانت جزءاً من وصف شكلي عام، واستعمل [النص القانوني ذي الصلة] و[موضوع النزاع] و[الوقائع] كعناصر نائبة.
- لا تحوّل المذكرة إلى ملخص أو تحليل قانوني للقضية.
- الناتج يجب أن يكون "تعليمات إنشاء" وليس المذكرة نفسها.

أخرج برومبتاً واحداً متكاملاً، مفصلاً، جاهزاً للنسخ إلى أي نموذج ذكاء اصطناعي. يجب أن يتضمن تعليمات واضحة للمستخدم النهائي لإدخال موضوع ووقائع وأطراف جديدة مكان العناصر النائبة، مع المحافظة على الهيكل والأسلوب والشكل المستخلص من النموذج.
ابدأ مباشرة بعنوان: "برومبت الوصف العكسي" ثم البرومبت فقط، دون مقدمات إضافية.`;

export async function POST(req: NextRequest) {
  const rl = await checkRateLimit(req, { key: 'tools-reverse-prompt', limit: 6, window: 60 });
  if (rl.limited) return NextResponse.json({ error: rl.errorMessage }, { status: 429 });
  try {
    const body = await req.json();
    const text = typeof body.text === 'string' ? body.text.trim() : '';
    if (!text) return NextResponse.json({ error: 'يرجى إدخال نص المذكرة.' }, { status: 400 });
    if (text.length > 120_000) return NextResponse.json({ error: 'النص طويل جداً. يرجى تقسيم المذكرة إلى أجزاء.' }, { status: 413 });

    const result = await callAI({
      systemPrompt: SYSTEM_PROMPT,
      userMessage: `حلّل النص التالي من حيث الشكل والبنية والأسلوب والصياغة فقط، واستخرج برومبت الوصف العكسي وفق القواعد السابقة. لا تكشف موضوع القضية أو الأطراف.\n\n--- بداية المذكرة ---\n${text}\n--- نهاية المذكرة ---`,
      requestType: 'legal_analysis',
      temperature: 0.2,
      maxTokens: 8192,
    });

    if (!result.content) return NextResponse.json({ error: result.timedOut ? 'استغرق التحليل وقتاً طويلاً، حاول مرة أخرى.' : 'فشل الاتصال بمحرك الذكاء الاصطناعي.' }, { status: 502 });
    return NextResponse.json({ prompt: result.content, model: result.model.label, modelId: result.model.id, usedFallback: result.usedFallback, elapsedMs: result.elapsedMs });
  } catch (error) {
    console.error('Reverse prompt error:', error);
    return NextResponse.json({ error: 'تعذر معالجة الطلب.' }, { status: 500 });
  }
}
